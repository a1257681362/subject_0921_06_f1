-- H2 本地文件数据库初始化脚本。F1 在此基础上补充业务表。
CREATE TABLE IF NOT EXISTS t_evops_schema_version (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_no VARCHAR(32) NOT NULL,
    description VARCHAR(255) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_evops_schema_version UNIQUE (version_no)
);

MERGE INTO t_evops_schema_version (version_no, description)
KEY (version_no)
VALUES ('base-0', 'EVOPS 初始工作区');

-- ============================================================
-- F1 印刷生产管理：机台台账 / 印单全量记录 / 印单作废反向记录
-- 约定：
--   1. 审计字段（request_no、operator、create_time、update_time、version）随每次写操作落库；
--   2. 删除只打 deleted 标记，不做物理删除；
--   3. 印单作废只新增反向记录（t_print_order_reversal），原单保留，追溯链不断。
-- ============================================================

-- 机台台账
CREATE TABLE IF NOT EXISTS t_print_machine (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    machine_code VARCHAR(64) NOT NULL,
    machine_name VARCHAR(128) NOT NULL,
    machine_model VARCHAR(128),
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    remark VARCHAR(512),
    request_no VARCHAR(64),
    operator VARCHAR(64),
    create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 1,
    deleted TINYINT NOT NULL DEFAULT 0,
    CONSTRAINT uk_print_machine_code UNIQUE (machine_code)
);

-- 印单全量记录：印单号唯一；用纸量按开数与克重估算，损耗加放单列
CREATE TABLE IF NOT EXISTS t_print_order (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_no VARCHAR(64) NOT NULL,
    order_date DATE NOT NULL,
    customer_name VARCHAR(128),
    product_name VARCHAR(128) NOT NULL,
    copies INT NOT NULL,
    sheet_split INT NOT NULL,
    grammage_g INT NOT NULL,
    paper_width_mm INT NOT NULL DEFAULT 787,
    paper_height_mm INT NOT NULL DEFAULT 1092,
    paper_sheets INT NOT NULL,
    waste_sheets INT NOT NULL DEFAULT 0,
    total_sheets INT NOT NULL,
    paper_weight_kg DECIMAL(12,3),
    machine_id BIGINT,
    status VARCHAR(16) NOT NULL DEFAULT 'NORMAL',
    remark VARCHAR(512),
    request_no VARCHAR(64),
    operator VARCHAR(64),
    create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 1,
    deleted TINYINT NOT NULL DEFAULT 0,
    CONSTRAINT uk_print_order_no UNIQUE (order_no)
);
CREATE INDEX IF NOT EXISTS idx_print_order_date ON t_print_order (order_date);
CREATE INDEX IF NOT EXISTS idx_print_order_status ON t_print_order (status);

-- 印单作废反向记录：只增不改不删；prev_reversal_id 串起同一印单的追溯链
CREATE TABLE IF NOT EXISTS t_print_order_reversal (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL,
    order_no VARCHAR(64) NOT NULL,
    reversal_no VARCHAR(96) NOT NULL,
    prev_reversal_id BIGINT,
    reason VARCHAR(512) NOT NULL,
    request_no VARCHAR(64),
    operator VARCHAR(64),
    create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 1,
    CONSTRAINT uk_print_reversal_no UNIQUE (reversal_no),
    CONSTRAINT fk_reversal_order FOREIGN KEY (order_id) REFERENCES t_print_order (id)
);
CREATE INDEX IF NOT EXISTS idx_reversal_order_id ON t_print_order_reversal (order_id);

MERGE INTO t_evops_schema_version (version_no, description)
KEY (version_no)
VALUES ('print-1', '印刷生产管理：机台台账、印单全量记录、作废反向记录');
